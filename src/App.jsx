function NewsForm({
  submitText,
  initialTitle = "",
  initialBody = "",
  onSubmit,
  onBack,
}) {
  const [form, setForm] = useState({
    title: initialTitle,
    content: initialBody,
  });
  const handleFormChange = (event) => {
    const { name, value } = event.target;

    /*
    기존 form 값은 유지하고
    입력한 항목만 변경
    */
    setForm((currentForm) => ({
      ...currentForm,
      [name]: value,
    }));
  }; // input 내용 변경 감

  /*
  CREATE 또는 UPDATE 버튼을 누르면 실행
  */
  const handleSubmit = (event) => {
    // form 제출 시 발생하는 새로고침 막기
    event.preventDefault();

    // 입력값 앞뒤의 공백 제거
    const title = form.title.trim();
    const content = form.content.trim();

    // 제목이나 내용이 비어 있으면 실행하지 않음
    if (!title || !content) {
      if (!title) {
        alert("제목을 입력하세요.");
      } else {
        alert("내용을 입력하세요.");
      }
      return;
    }

    /*
    부모가 전달한 함수 실행

    Create 화면에서는 handleCreate가 실행되고,
    Update 화면에서는 handleUpdate가 실행된다.
    */
    onSubmit(title, content);
  };
  return (
    <article className="container-detail">
      <form onSubmit={handleSubmit}>
        <h1 className="list-detail__title">
          <TextField
            hiddenLabel
            id="outlined-multiline-static"
            placeholder="제목을 입력하세요."
            multiline
            name="title"
            value={form.title}
            onChange={handleFormChange}
          />
        </h1>

        <div className="list-detail__content">
          <TextField
            hiddenLabel
            id="outlined-multiline-content"
            placeholder="내용을 입력하세요."
            multiline
            rows={4}
            name="content"
            value={form.content}
            onChange={handleFormChange}
          />
        </div>
        <div className="list-detail__action">
          <Button type="button" startIcon={<ArrowBackIcon />} onClick={onBack}>
            목록
          </Button>
          <div className="col right">
            <Button variant="contained" endIcon={<SendIcon />} type="submit">
              {submitText}
            </Button>
          </div>
        </div>
      </form>
    </article>
  );
}

export default function App() {
  /**State */
  const [value, setValue] = useState("전체"); //tab
  const [itemList, setItemList] = useState(itemData); //list item
  const [mode, setMode] = useState("LIST"); //페이지 변경 모드
  const [selectedItem, setSelectedItem] = useState(null); //현재 선택된 아이템
  const visibleItems =
    value === "전체"
      ? itemList
      : itemList.filter((item) => item.category === value);

  /**Function */
  //tab 함수
  const handleChange = (event, newValue) => {
    setValue(newValue);
  };
  //리스트 상세보기
  const handleRead = (event, item) => {
    event.preventDefault();
    setSelectedItem(item);
    setMode("DETAIL");
  };
  //Detail 목록 버튼
  const handleBackToList = (event) => {
    event.preventDefault();
    setMode("LIST");
  };

  /*Update 버튼 클릭- 글 수정 화면으로 이동*/
  const handleSelectUpdate = () => {
    setMode("UPDATE");
  };
  /*기존 게시글 수정*/
  const handleUpdate = (id, title, content) => {
    const updatedItem = {
      ...selectedItem,
      title,
      content,
    };

    setItemList((currentItems) =>
      currentItems.map((item) => (item.id === id ? updatedItem : item)),
    );

    setSelectedItem(updatedItem);
    setMode("DETAIL");
  };

  /**삭제 */
  const handleDelete = (id) => {
    setItemList((currentItems) =>
      currentItems.filter((item) => item.id !== id),
    );
    setMode("LIST");
  };

  /**생성 */
  const handleCreateClick = () => {
    setMode("CREATE");
  };
  const handleCreate = (title, content) => {
    const newItem = {
      id: crypto.randomUUID(),
      category: "기획기사",
      type: "카드뉴스",
      title,
      description: content,
      content,
      date: new Date().toLocaleDateString("ko-KR"),
      image: "https://images.unsplash.com/photo-1558642452-9d2a7deb7f62",
    };

    setItemList((currentItems) => [...currentItems, newItem]);
    setSelectedItem(newItem);
    setMode("DETAIL");
  };

  // JSX 안에서 익명 함수를 만들지 않도록 이벤트 연결용 handler 분리
  const handleSelectedDelete = () => {
    handleDelete(selectedItem.id);
  };

  const handleSelectedUpdate = (title, content) => {
    handleUpdate(selectedItem.id, title, content);
  };
  /** mode 변경  */
  let content;
  switch (mode) {
    case "LIST":
      content = (
        <NewsList
          value={value}
          onTabChange={handleChange}
          items={visibleItems}
          onRead={handleRead}
          onCreateClick={handleCreateClick}
        />
      );
      break;

    case "DETAIL":
      content = (
        <NewsDetail
          item={selectedItem}
          onBack={handleBackToList}
          onSelectUpdate={handleSelectUpdate}
          onDelete={handleSelectedDelete}
        />
      );
      break;

    case "UPDATE":
      content = (
        <NewsForm
          submitText="완료"
          initialTitle={selectedItem.title}
          initialBody={selectedItem.content}
          onBack={handleBackToList}
          onSubmit={handleSelectedUpdate}
        ></NewsForm>
      );
      break;

    case "CREATE":
      content = (
        <NewsForm
          submitText="완료"
          onBack={handleBackToList}
          onSubmit={handleCreate}
        ></NewsForm>
      );
      break;

    default:
      content = null;
      break;
  }

  return (
    <div className="container">
      <Header onBack={handleBackToList} />
      {content}
    </div>
  );
}
